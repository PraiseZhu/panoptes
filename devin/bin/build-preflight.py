#!/usr/bin/env python3
"""Bundle the Devin Preflight scripts into self-contained single files (PraiseZhu/panoptes#312).

Usage: build-preflight.py [--check] [--out-dir DIR]

A Preflight script runs alone on Devin's Minimal VM (no repo checkout), so each bundle embeds the sources it imports:
  devin/preflight/dist/mergewatch.bundle.py <- gh_app_jwt.py + mergewatch.py
  devin/preflight/dist/catchup.bundle.py    <- gh_app_jwt.py + mergewatch.py + catchup.py
Each module is executed from its embedded source into sys.modules in dependency order, then the entry module's main() runs.
Output is deterministic (no time stamps, sorted inputs). Paste a bundle into the automation's Preflight script.
--check: build in memory and exit 1 when a committed bundle differs from its sources or exceeds 262144 bytes
(Devin's 256 KiB script limit). --out-dir: write there instead of devin/preflight/dist (tests).
Exit: 0 ok, 1 stale / oversized bundle, 2 usage.
"""
import argparse
import hashlib
import os
import sys

DEVIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(DEVIN, "preflight")
DIST = os.path.join(SRC, "dist")
MAX_BYTES = 262144
BUNDLES = {
    "mergewatch.bundle.py": ("mergewatch", ["gh_app_jwt", "mergewatch"]),
    "catchup.bundle.py": ("catchup", ["gh_app_jwt", "mergewatch", "catchup"]),
}

TEMPLATE = '''#!/usr/bin/env python3
# GENERATED by devin/bin/build-preflight.py — do not edit; change devin/preflight/*.py and rebuild.
# Devin Preflight bundle: {entry} (PraiseZhu/panoptes#312). Modules: {modules}
# Source sha256: {digests}
import sys
import types

_SOURCES = {{
{sources}
}}


def _load(name):
    module = types.ModuleType(name)
    module.__file__ = __file__
    sys.modules[name] = module
    exec(compile(_SOURCES[name], "<bundle>/" + name + ".py", "exec"), module.__dict__)
    return module


for _name in {order!r}:
    _load(_name)

if __name__ == "__main__":
    sys.exit(sys.modules[{entry!r}].main())
'''


def read_source(name):
    with open(os.path.join(SRC, f"{name}.py"), encoding="utf-8") as f:
        return f.read()


def to_bundle(entry, order):
    sources = {name: read_source(name) for name in order}
    digests = " ".join(f"{n}={hashlib.sha256(s.encode()).hexdigest()[:16]}" for n, s in sources.items())
    body = "\n".join(f"    {name!r}: {src!r}," for name, src in sources.items())
    return TEMPLATE.format(entry=entry, modules=", ".join(order), digests=digests, sources=body, order=order)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out-dir", default=DIST)
    args = ap.parse_args(argv)
    bad = []
    for fname, (entry, order) in sorted(BUNDLES.items()):
        text = to_bundle(entry, order)
        size = len(text.encode("utf-8"))
        path = os.path.join(args.out_dir, fname)
        if size > MAX_BYTES:
            bad.append(f"{fname}: {size} bytes > {MAX_BYTES}")
        if args.check:
            try:
                with open(path, encoding="utf-8") as f:
                    current = f.read()
            except OSError:
                current = None
            if current != text:
                bad.append(f"{fname}: out of date with devin/preflight sources (run devin/bin/build-preflight.py)")
            else:
                print(f"ok   {fname} ({size} bytes)")
            continue
        os.makedirs(args.out_dir, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.chmod(path, 0o755)
        print(f"wrote {os.path.relpath(path)} ({size} bytes)")
    for b in bad:
        print(f"build-preflight: {b}", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
